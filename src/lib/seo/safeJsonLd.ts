/*
 * toSafeJsonLdString — найдено при ревизии кода (август 2026): все места,
 * вставляющие JSON-LD через `set:html={JSON.stringify(x)}`, были уязвимы
 * к разрыву тега `<script>`, если строковое значение внутри объекта
 * когда-нибудь буквально содержит "</script>" — `JSON.stringify` не
 * экранирует "<". Практический риск сегодня низкий (данные редакционные/
 * плейсхолдер), но это стандартная, дешёвая защита (рекомендация OWASP —
 * экранировать "<" как "<" перед вставкой JSON в HTML), а не
 * гипотетическая проблема: JSON.parse корректно раскрывает "<"
 * обратно в "<", так что для потребителя JSON-LD (поисковики, structured
 * data testing tool) вывод не отличается.
 */
export function toSafeJsonLdString(data: unknown): string {
  return JSON.stringify(data).replace(/</g, "\\u003c");
}
